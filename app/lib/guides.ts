export const guides = allGuides.filter((g) => g.published <= buildDate);

export function getGuide(slug: string): Guide | undefined {
	return guides.find((g) => g.slug === slug);
}

// 본문 문자열을 글자·링크 조각으로 나눈다: "[이미지 변환](/tools/image-converter)"
export function segments(text: string): { text: string; href?: string }[] {
	const out: { text: string; href?: string }[] = [];
	const re = /\[([^\]]+)\]\(([^)]+)\)/g;
	let last = 0;
	for (const m of text.matchAll(re)) {
		if (m.index > last)
			out.push({ text: text.slice(last, m.index) });
		out.push({ text: m[1]!, href: m[2]! });
		last = m.index + m[0].length;
	}
	if (last < text.length) out.push({ text: text.slice(last) });
	return out;
}

// 템플릿에서 블록 종류별로 그리기 쉽게 풀어 둔다
export interface FlatBlock {
	p?: string;
	ol?: string[];
	ul?: string[];
	note?: string;
	table?: { head: string[]; rows: string[][] };
}

export function blockOf(b: GuideBlock): FlatBlock {
	return typeof b === 'string' ? { p: b } : b;
}

// "2026-11-17" -> "2026년 11월 17일"
export function koDate(iso: string): string {
	const [y, m, d] = iso.split('-').map(Number);
	return `${y}년 ${m}월 ${d}일`;
}
